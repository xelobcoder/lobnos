"use client";

import { useState, useEffect } from "react";
import { customFetch } from "../../../components/Auth/customFetch";
import Loader from "../../../components/isLoading";
import PrimeTable from "../../../components/accessories/Datatables/PrimeTable";

interface Receipt {
     id: number;
     billingid: number;
     generated_receipt_number: string;
     generated_at: string;
     printed_at: string | null;
     printed: number;
     generated_by_name: string;
     printed_by_name: string | null;
}

interface ReceiptsResponse {
     status: string;
     data: {
          receipts: Receipt[];
          total: number;
     };
}

export default function ReceiptsPage() {
     const [receipts, setReceipts] = useState<Receipt[]>([]);
     const [total, setTotal] = useState<number>(0);
     const [loading, setLoading] = useState(true);
     const [error, setError] = useState<string | null>(null);

     const fetchReceipts = async () => {
          try {
               setLoading(true);
               setError(null);
               const response: ReceiptsResponse = await customFetch('receipts');
               if (response?.status === 'success' && response?.data) {
                    setReceipts(response.data.receipts);
                    setTotal(response.data.total);
               } else {
                    throw new Error('Failed to fetch receipts');
               }
          } catch (err: any) {
               setError(err?.message || 'Failed to load receipts');
          } finally {
               setLoading(false);
          }
     };


     const handleSeverSideProcessing = async (pagination: { page: number, count: number, sortby: "ASC" | 'DESC' }) => {
          try {
               setLoading(true);
               setError(null);
               const response: ReceiptsResponse = await customFetch(`receipts?page=${pagination.page}&count=${pagination.count}&sortBy=${pagination.sortby || 'DESC'}`);
               if (response?.status === 'success' && response?.data && response.data.receipts.length > 0) {
                    return { result: response.data.receipts, error: false };
               } else {
                    return { result: [], error: false };
               }
          } catch (err: any) {
               return {
                    result: [], error: false
               };
          }

     }

     useEffect(() => {
          fetchReceipts();
     }, []);

     const columns = [
          {
               Header: 'ID',
               accessor: 'id',
          },
          {
               Header: 'Billing ID',
               accessor: 'billingid',
          },
          {
               Header: 'Receipt Number',
               accessor: 'generated_receipt_number',
          },
          {
               Header: 'Generated At',
               accessor: 'generated_at',
               Cell: ({ value }: { value: string }) => new Date(value).toLocaleString(),
          },
          {
               Header: 'Printed At',
               accessor: 'printed_at',
               Cell: ({ value }: { value: string | null }) =>
                    value ? new Date(value).toLocaleString() : 'Not printed',
          },
          {
               Header: 'Status',
               accessor: 'printed',
               Cell: ({ value }: { value: number }) => (
                    <span className={`badge ${value === 1 ? 'bg-success' : 'bg-warning'}`}>
                         {value === 1 ? 'Printed' : 'Not Printed'}
                    </span>
               ),
          },
          {
               Header: 'Generated By',
               accessor: 'generated_by_name',
          },
          {
               Header: 'Printed By',
               accessor: 'printed_by_name',
               Cell: ({ value }: { value: string | null }) => value || 'N/A',
          },
     ];



     if (receipts.length === 0) {
          return (
               <div className="container-fluid px-4 py-3">
                    <div className="row">
                         <div className="col-12">
                              <h4 className="mb-4">Receipts</h4>
                              {loading ? (
                                   <Loader />
                              ) : error ? (
                                   <div className="alert alert-danger">{error}</div>
                              ) : (
                                   <div className="text-center py-4">
                                        <p className="text-muted">No receipts found</p>
                                   </div>
                              )}
                         </div>
                    </div>
               </div>
          );
     }
     return (
          <div className="container-fluid px-4 py-3">
               <PrimeTable
                    column={columns}
                    data={receipts}
                    filtering={true}
                    isExpoerted={false}
                    serverSideFiltering={true}
                    handleSeverSideProcessing={handleSeverSideProcessing}
               />
          </div>
     );
}
